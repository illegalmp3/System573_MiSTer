// -----------------------------------------------------------------------------
// k573dio_cpld.v - digital I/O board XC9536 CPLD: FPGA configuration port
//                  (0x1f6400f0-0x1f6400ff)
//
// Sources (docs/2026-10-23-hw-audit-573in1-sources.md, "psx-spx" section):
//  * psx-spx dev "Expansion I/O Boards", 0x1f6400f4/f6/f8: the CPLD answers with
//    no bitstream loaded; ALL of 0xf0-0xff read back the 0xf6 status word
//    (incomplete decode); status bit 12 = /INIT from the FPGA, bit 13 = DONE;
//    control writes bit 12 = /INIT, 13 = DONE, 14 = /PROGRAM to the FPGA; Konami
//    writes 0x8000, 0xc000, 0xf000 before streaming the bitstream LSB-first, one
//    bit per 0xf8 write (bit 15), slave-serial, CCLK generated by the CPLD.
//  * spicyjpeg/573in1 src/common/io.cpp loadDigitalIORawBitstream: the same
//    0x8000/0xc000/0xf000 sequence, then requires /INIT = 1, DONE = 0 before the
//    upload and /INIT = DONE = 1 after it (3 attempts, then "upload failed").
//  * Board ID bits: bit 15 = 1, bit 14 = 0. This is what MAME (constant 0xb000),
//    573in1 isDigitalIOPresent() and ddrsbm (`& 0xc000 == 0x8000`) all use; the
//    psx-spx table lists 14/15 the other way round.
//  * XC4000/Spartan-XL serial stream (checked on 573in1 data/fpga.bit): >= 4 dummy
//    1s, preamble 0010, 24-bit length count MSB first. DONE rises once that many
//    bits have been clocked in; 330,696 bits (psx-spx: "always 330696 bits") is
//    the fallback if no preamble is seen. 573in1's fpga.bit: 330,696 bits, length
//    count 330,689 -- so DONE rises 7 bits before the end of the stream.
//    "LSB first" is the byte storage order only: Konami and 573in1 both reverse
//    it in software, so the serial order on DIN is always the Xilinx one.
//
// Before this module the status was MAME's constant 0xb000 (DONE always high), so
// 573in1 saw DONE before it had sent a single bit and gave up. After a complete
// upload the status is 0xb000 again, which is all Konami's driver checks.
//
// The FPGA-side registers (0x80-0xef) stay modelled as Konami's bitstream in
// k573dio.v whether or not an upload happened; only this status port changes.
//
// Verilog-2005. Released under the GNU GPL v2.
// -----------------------------------------------------------------------------
module k573dio_cpld #(
    // /INIT low after /PROGRAM rises (FPGA memory clear). Bounds from sources:
    // MAME reports /INIT = 1 at all times and every Konami title boots on it, so
    // Konami's driver tolerates an instant clear; 573in1 samples 5 ms after its
    // 0xf000 write. 64 clocks (~2 us) sits inside both.
    parameter integer INIT_CLKS   = 64,
    parameter integer DEFAULT_LEN = 330696    // bits; used only if no preamble is found
)(
    input  wire        clk,
    input  wire        rst,
    input  wire        we,          // write strobe for 0xf0-0xff
    input  wire [3:0]  off,         // byte offset & 0xf
    input  wire [15:0] din,
    output wire [15:0] status,      // read value for ALL of 0xf0-0xff
    output wire        fpga_done    // observability
);
    // CPLD control latch: [3]=bit15 (unused, Konami writes 1), [2]=/PROGRAM,
    // [1]=DONE drive, [0]=/INIT drive. Open-drain: 0 holds the line low.
    reg [3:0]  ctl;
    // FPGA configuration state
    localparam [1:0] C_CLEAR = 2'd0, C_LOAD = 2'd1, C_DONE = 2'd2;
    reg [1:0]  cst;
    reg [12:0] clr_cnt;
    reg [18:0] nbits;               // bits clocked in since /INIT went high
    reg [2:0]  ones;                // consecutive 1s (saturating at 4)
    reg [2:0]  pre;                 // preamble match progress 0..4 (4 = in length)
    reg        have_len;
    reg [4:0]  len_bits;
    reg [23:0] len;

    wire prog_n   = ctl[2];
    wire init_n   = (cst != C_CLEAR) & ctl[0];
    wire done_pin = (cst == C_DONE) & ctl[1];
    wire bit_in   = din[15];

    assign status    = {1'b1, 1'b0, done_pin, init_n, 12'h000};
    assign fpga_done = (cst == C_DONE);

    always @(posedge clk) begin
        if (rst) begin
            ctl <= 4'b1111;                          // released
            cst <= C_CLEAR; clr_cnt <= INIT_CLKS[12:0]; // power-on clear
            nbits <= 19'd0; ones <= 3'd0; pre <= 3'd0;
            have_len <= 1'b0; len_bits <= 5'd0; len <= 24'd0;
        end else begin
            if (we && off == 4'h6) ctl <= din[15:12];

            if (!prog_n) begin
                // /PROGRAM low: configuration memory cleared, /INIT held low
                cst <= C_CLEAR; clr_cnt <= INIT_CLKS[12:0];
                nbits <= 19'd0; ones <= 3'd0; pre <= 3'd0;
                have_len <= 1'b0; len_bits <= 5'd0; len <= 24'd0;
            end else if (cst == C_CLEAR) begin
                // clearing; the FPGA releases /INIT afterwards -- unless the CPLD
                // is still holding /INIT low (Konami's 0xc000 step), which delays it
                if (clr_cnt != 13'd0) clr_cnt <= clr_cnt - 13'd1;
                else if (ctl[0])      cst <= C_LOAD;
            end else if (cst == C_LOAD && we && off == 4'h8) begin
                nbits <= nbits + 19'd1;
                if (!have_len) begin
                    if (pre == 3'd0) begin
                        if (bit_in) ones <= (ones == 3'd4) ? 3'd4 : ones + 3'd1;
                        else if (ones == 3'd4) pre <= 3'd1;      // 1st preamble 0
                        else ones <= 3'd0;
                    end else if (pre == 3'd1) begin             // expect 0
                        if (!bit_in) pre <= 3'd2; else begin pre <= 3'd0; ones <= 3'd1; end
                    end else if (pre == 3'd2) begin             // expect 1
                        if (bit_in) pre <= 3'd3; else begin pre <= 3'd0; ones <= 3'd0; end
                    end else if (pre == 3'd3) begin             // expect 0 -> length follows
                        if (!bit_in) pre <= 3'd4; else begin pre <= 3'd0; ones <= 3'd1; end
                    end else begin                              // 24 length bits, MSB first
                        len <= {len[22:0], bit_in};
                        len_bits <= len_bits + 5'd1;
                        if (len_bits == 5'd23) have_len <= 1'b1;
                    end
                end
                // DONE once the length count is reached (this write included)
                if ((have_len && ({5'd0, nbits} + 24'd1 >= len)) ||
                    (nbits + 19'd1 >= DEFAULT_LEN[18:0]))
                    cst <= C_DONE;
            end
        end
    end
endmodule
