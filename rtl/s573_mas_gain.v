// -----------------------------------------------------------------------------
// s573_mas_gain.v - the MAS3507D output gain, applied to the MP3 PCM
//
// WHY (2026-10-20, DrumMania 2nd/3rd Mix): the games set the MP3 decoder's output
// level through the MAS3507D gain matrix (I2C WRITE_MEM bank 1, 0x7f8 = L->L,
// 0x7fb = R->R; rtl/mas3507d_i2c.v captures both). DrumMania plays songs at -12 dB
// and MUTES the music (gain 0) when it wants it gone, then stops the stream later or
// lets it run out. The core captured every write but never applied it, so the
// music ran on after screen changes and drowned the SPU drum sounds by ~6 dB. The
// DDR titles write it too (-10 dB ddr3mj, -12 dB, -64 dB fades), so this is the
// level MAME and the real board play every title at.
//
// MAME mas3507d.cpp (BSD-3), the reference this transliterates:
//   gain_to_db(v)         = round(20 * log10((0x100000 - v) / 0x80000))
//   gain_to_percentage(v) = v == 0 ? 0 : powf(10, (db + 6) / 20)
//   device_reset: gain_ll = gain_rr = 1.0;  every output sample *= gain
// The dB step and the percentage are a pure function of v, so they come from a
// table generated by tools/gen_mas_gain_rom.py with MAME's exact arithmetic
// (C round, powf). db is monotonic in x = 0x100000 - v: the first table entry
// (scanning from +6 dB down) whose threshold x <= x is the step. A write starts a
// ~110-cycle scan per channel; the old gain holds until the new one is ready.
//
// Applied at the OUTPUT (after the elastic buffer) so a mute takes effect at once,
// not after the ~1.5 s of decoded PCM already queued in the ring.
//
// Verilog-2005. Released under the GNU GPL v2.
// -----------------------------------------------------------------------------
module s573_mas_gain (
    input  wire               clk,
    input  wire               rst,
    input  wire [19:0]        gain_ll,     // mas3507d_i2c captured matrix
    input  wire [19:0]        gain_rr,
    input  wire               gain_stb,    // 1-cycle pulse per completed matrix write
    input  wire signed [15:0] in_l,
    input  wire signed [15:0] in_r,
    output reg  signed [15:0] out_l,
    output reg  signed [15:0] out_r,
    output reg  [14:0]        q_l,         // current Q12 gains (observability / tests)
    output reg  [14:0]        q_r
);
    // ---- BEGIN GENERATED gain table (tools/gen_mas_gain_rom.py, MAME mas3507d.cpp
    // gain_to_db / gain_to_percentage; do not edit). Entries run from +6 dB down;
