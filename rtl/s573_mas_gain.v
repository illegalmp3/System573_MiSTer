            7'd104: gain_rom = {21'd6, 15'd0};   // -99 dB
            7'd105: gain_rom = {21'd5, 15'd0};   // -100 dB
            7'd106: gain_rom = {21'd4, 15'd0};   // -102 dB
            7'd107: gain_rom = {21'd3, 15'd0};   // -105 dB
            7'd108: gain_rom = {21'd2, 15'd0};   // -108 dB
            7'd109: gain_rom = {21'd1, 15'd0};   // -114 dB
            default: gain_rom = {21'd1, 15'd0};
            endcase
        end
    endfunction
    // ---- END GENERATED gain table

    localparam [14:0] UNITY = 15'd4096;    // MAME device_reset: 1.0

    // ---- dB-step scan: one channel at a time ----
    reg        pend;           // a write arrived (latched until the scan takes it)
    reg        busy;
    reg        ch;             // 0 = L, 1 = R
    reg  [6:0] idx;
    reg [20:0] x;              // 0x100000 - v of the channel being scanned
    reg [19:0] v_l, v_r;       // the values being converted
    wire [35:0] row = gain_rom(idx);
    wire [20:0] thr = row[35:15];
    wire [14:0] q   = row[14:0];

    always @(posedge clk) begin
        if (rst) begin
            q_l <= UNITY; q_r <= UNITY;
            pend <= 1'b0; busy <= 1'b0; ch <= 1'b0; idx <= 7'd0; x <= 21'd0;
            v_l <= 20'd0; v_r <= 20'd0;
        end else begin
            if (gain_stb) pend <= 1'b1;
            if (!busy && (pend || gain_stb)) begin
                pend <= 1'b0;
                busy <= 1'b1;
                ch   <= 1'b0;
                idx  <= 7'd0;
                v_l  <= gain_ll;
                v_r  <= gain_rr;
                x    <= 21'h100000 - {1'b0, gain_ll};
            end else if (busy) begin
                if ((ch ? v_r : v_l) == 20'd0 || x >= thr || idx == GAIN_N - 1) begin
                    // MAME: v == 0 is a mute; otherwise the first step whose
                    // threshold x reaches. (idx == GAIN_N-1 cannot be passed: its
                    // threshold is x = 1, the smallest x there is.)
                    if (!ch) begin
                        q_l <= (v_l == 20'd0) ? 15'd0 : q;
                        ch  <= 1'b1;
                        idx <= 7'd0;
                        x   <= 21'h100000 - {1'b0, v_r};
                    end else begin
                        q_r  <= (v_r == 20'd0) ? 15'd0 : q;
                        busy <= 1'b0;
                    end
                end else begin
                    idx <= idx + 7'd1;
                end
            end
        end
    end

    // ---- apply: sample * Q12, saturate to 16 bits (registered) ----
    wire signed [31:0] pl = in_l * $signed({1'b0, q_l});
    wire signed [31:0] pr = in_r * $signed({1'b0, q_r});
    wire signed [19:0] sl = pl[31:12];
    wire signed [19:0] sr = pr[31:12];
    function signed [15:0] sat16;
        input signed [19:0] a;
        begin
            if (a > 20'sd32767)       sat16 = 16'sd32767;
            else if (a < -20'sd32768) sat16 = -16'sd32768;
            else                      sat16 = a[15:0];
        end
    endfunction
    always @(posedge clk) begin
        if (rst) begin
            out_l <= 16'sd0; out_r <= 16'sd0;
        end else begin
            out_l <= sat16(sl);
            out_r <= sat16(sr);
        end
    end
endmodule
