`timescale 1ns/1ps
// tb_gn845pwbb.v - GN845-PWB(B) stage multiplexor: replay the boot handshake
// (13-bit ID 0x0c90 clocked LSB-first, then 22 clocks) on stage 0 and check the
// JAMMA mask after every clock against an independent Python model of MAME's
// gn845pwbb_clk_w. Also: en=0 (Solo cab) never masks; a Solo-style lamp pattern
// that is not 0x0c90 never leaves IDLE.
module tb_gn845pwbb;
    reg clk = 0, rst = 1, en = 1;
    reg [31:0] lamp = 32'hffff_ffff;   // lamp bit HIGH = line idle (DO/CLK read inverted)
    wire [15:0] stage_mask;
    gn845pwbb dut(.clk(clk), .rst(rst), .en(en), .lamp(lamp), .stage_mask(stage_mask));
    always #5 clk = ~clk;
    integer errors = 0, i;
    // stimulus + expectation (generated by the Python reference in the commit)
    reg [0:34]   dobits;
    reg [15:0]   expm [0:34];
    task chk(input [15:0] got, input [15:0] exp, input integer n);
        if (got !== exp) begin $display("FAIL: after clock %0d mask=%04h expected %04h", n, got, exp); errors = errors + 1; end
    endtask
    // one stage-0 clock: set DO (lamp[4] = ~DO), then CLK rising = lamp[7] 1->0, then release
    task clk0(input do_bit);
        begin
            lamp[4] = ~do_bit; @(negedge clk);
            lamp[7] = 1'b0;    @(negedge clk); @(negedge clk);   // clk rises (inverted)
            lamp[7] = 1'b1;    @(negedge clk);
        end
    endtask
    initial begin
        dobits = 35'b0000100100110_0000000000000000000000;
        expm[0]=16'hffff; expm[1]=16'hffff; expm[2]=16'hffff; expm[3]=16'hffff; expm[4]=16'hffff;
        expm[5]=16'hffff; expm[6]=16'hffff; expm[7]=16'hffff; expm[8]=16'hffff; expm[9]=16'hffff;
        expm[10]=16'hffff; expm[11]=16'hffff; expm[12]=16'hf9f9;
        expm[13]=16'hfff9; expm[14]=16'hfbf9; expm[15]=16'hfdf9; expm[16]=16'hf9f9; expm[17]=16'hfdf9;
        expm[18]=16'hf9f9; expm[19]=16'hfdf9; expm[20]=16'hf9f9; expm[21]=16'hfdf9; expm[22]=16'hf9f9;
        expm[23]=16'hfdf9; expm[24]=16'hf9f9; expm[25]=16'hfdf9; expm[26]=16'hf9f9; expm[27]=16'hfdf9;
        expm[28]=16'hf9f9; expm[29]=16'hfdf9; expm[30]=16'hf9f9; expm[31]=16'hfdf9; expm[32]=16'hf9f9;
        expm[33]=16'hfdf9; expm[34]=16'hffff;
        repeat (3) @(negedge clk); rst = 0; @(negedge clk);
        chk(stage_mask, 16'hffff, -1);
        for (i = 0; i < 35; i = i + 1) begin clk0(dobits[i]); chk(stage_mask, expm[i], i); end
        // Solo cab: same handshake, en=0 -> never masked
        en = 0; rst = 1; @(negedge clk); rst = 0; @(negedge clk);
        for (i = 0; i < 35; i = i + 1) begin clk0(dobits[i]); if (stage_mask !== 16'hffff) begin $display("FAIL: en=0 masked %04h at %0d", stage_mask, i); errors = errors + 1; end end
        // wrong ID never arms
        en = 1; rst = 1; @(negedge clk); rst = 0; @(negedge clk);
        for (i = 0; i < 40; i = i + 1) begin clk0(i[0]); if (stage_mask !== 16'hffff) begin $display("FAIL: bogus ID armed %04h at %0d", stage_mask, i); errors = errors + 1; end end
        if (errors == 0) $display("RESULT: PASS (gn845pwbb)"); else $display("RESULT: FAIL (gn845pwbb, %0d errors)", errors);
        $finish;
    end
endmodule
