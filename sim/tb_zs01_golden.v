`timescale 1ns/1ps
// tb_zs01_golden.v -- the ZS01 against an INDEPENDENT reference, byte for byte.
//
// sim/tb_zs01.v scrambles commands and descrambles responses with its own
// transliteration of the cipher. That proves the RTL is self-consistent and nothing
// else: a wrong algorithm that is wrong the same way in both directions passes it.
// It also passed for months while the engine sat inside a translate_off block that
// Quartus deleted (docs/2026-09-13-zs01-engine-never-synthesized.md).
//
// This bench runs NO cipher. tools/zs01_ref.py -- a Python transcription of MAME's
// zs01.cpp that shares no code with rtl/zs01.v -- produced, from the real ddrusa
// cassette, the exact ciphertext a 573 game puts on SDA and the exact ciphertext the
// cassette must answer. The bench loads that cassette image through the load port,
// clocks the host bytes in, and compares the response bytes. If the RTL's cipher,
// CRC, chaining, stale-buffer behaviour or key handling differ from MAME in ANY
// direction, the bytes differ.
//
// Self-skips (PASS with a notice) when the ddrusa dump is absent -- the fixtures are
// generated by sim/gen_secdata.sh from dumps/mame573/ddrusa.zip and never committed.
module tb_zs01_golden;
    reg  clk = 0, rst = 1;
    reg  cs = 1, sec_rst = 0, scl = 0, sda_m = 1;
    wire sda_o;
    integer errors = 0;

    reg        L_we = 0;  reg [12:0] L_addr = 0;  reg [7:0] L_data = 0;
    reg        Lds_we = 0; reg [2:0] Lds_addr = 0; reg [7:0] Lds_data = 0;

    zs01 dut (
        .clk(clk), .rst(rst), .cs(cs), .sec_rst(sec_rst),
        .scl(scl), .sda_i(sda_m), .sda_o(sda_o),
        .load_we(L_we), .load_addr(L_addr), .load_data(L_data),
        .load_ds_we(Lds_we), .load_ds_addr(Lds_addr), .load_ds_data(Lds_data)
    );

    always #5 clk = ~clk;
    task tk; begin repeat (3) @(posedge clk); end endtask

    // ---- I2C master primitives (same timing as tb_zs01.v) ----
    task i2c_start; begin
        scl = 0; tk; sda_m = 1; tk; scl = 1; tk; sda_m = 0; tk; scl = 0; tk;
    end endtask
    task send_byte(input [7:0] d);
        integer i; begin
            for (i = 7; i >= 0; i = i - 1) begin scl = 0; tk; sda_m = d[i]; tk; scl = 1; tk; end
            scl = 0; tk; sda_m = 1; tk; scl = 1; tk; scl = 0; tk;   // 9th clock = device ack
        end
    endtask
    task read_byte(output [7:0] d);
        integer i; begin
            d = 8'h00;
            for (i = 7; i >= 0; i = i - 1) begin
                scl = 0; tk; sda_m = 1; tk; scl = 1; tk; d[i] = sda_o;
            end
            scl = 0; tk; sda_m = 1'b0; tk; scl = 1; tk; scl = 0; tk; sda_m = 1; // master ack
        end
    endtask
    task read_rtr_byte(output [7:0] d);
        integer i; begin
            d = 8'h00;
            for (i = 0; i < 8; i = i + 1) begin scl = 1; tk; scl = 0; tk; d = {d[6:0], sda_o}; end
        end
    endtask

    // ---- fixtures ----
    reg [7:0] u1  [0:4115];
    reg [7:0] u6  [0:7];
    reg [7:0] vec [0:1023];     // [0] = count, then 24 bytes per vector
    integer   fh, k, v, n, nvec, bad;
    reg       present;
    reg [7:0] b0, b1, b2, b3, got;
    reg [7:0] resp [0:11];

    initial begin
        present = 1'b0;
        fh = $fopen("secdata/ddrusa_zs01_vectors.hex", "r");
        if (fh != 0) begin
            $fclose(fh);
            for (k = 0; k < 4116; k = k + 1) u1[k] = 8'h00;
            $readmemh("secdata/ddrusa_u1.hex", u1);
            $readmemh("secdata/ddrusa_u6.hex", u6);
            $readmemh("secdata/ddrusa_zs01_vectors.hex", vec);
            present = 1'b1;
        end

        if (!present) begin
            $display("tb_zs01_golden: secdata/ddrusa_zs01_vectors.hex absent (no ddrusa dump) -- SKIPPED");
            $display("RESULT: PASS");
            $finish;
        end

        // ---- load the real cassette through the load port (140 image bytes + .u6) ----
        repeat (4) @(posedge clk);
        for (k = 0; k < 140; k = k + 1) begin
            @(negedge clk); L_we = 1; L_addr = k[12:0]; L_data = u1[k];
        end
        @(negedge clk); L_we = 0;
        for (k = 0; k < 8; k = k + 1) begin
            @(negedge clk); Lds_we = 1; Lds_addr = k[2:0]; Lds_data = u6[k];
        end
        @(negedge clk); Lds_we = 0;
        repeat (4) @(posedge clk); @(negedge clk); rst = 0; tk;

        // ---- response to reset ----
        cs = 0; tk;
        sec_rst = 1; tk;
        read_rtr_byte(b0); read_rtr_byte(b1); read_rtr_byte(b2); read_rtr_byte(b3);
        if ({b0,b1,b2,b3} !== 32'h5a53_0001) begin
            $display("FAIL: rtr = %02h%02h%02h%02h (expected 5a530001)", b0, b1, b2, b3);
            errors = errors + 1;
        end

        // ---- replay every vector: raw bytes in, raw bytes out, no cipher here ----
        nvec = vec[0];
        $display("tb_zs01_golden: %0d vectors from the ddrusa cassette", nvec);
        for (v = 0; v < nvec; v = v + 1) begin
            i2c_start;
            for (k = 0; k < 12; k = k + 1) send_byte(vec[1 + 24*v + k]);
            // The real ZS01 is a PIC that takes hundreds of microseconds per packet and
            // the host waits for it; the engine needs ~70 clocks (a 0xFD erase ~250).
            repeat (1000) @(posedge clk);
            for (k = 0; k < 12; k = k + 1) read_byte(resp[k]);
            bad = 0;
            for (k = 0; k < 12; k = k + 1)
                if (resp[k] !== vec[1 + 24*v + 12 + k]) bad = bad + 1;
            if (bad != 0) begin
                errors = errors + 1;
                $display("FAIL: vector %0d: %0d of 12 response bytes differ", v, bad);
                $write("       expected:"); for (k = 0; k < 12; k = k + 1) $write(" %02h", vec[1 + 24*v + 12 + k]); $write("\n");
                $write("       got     :"); for (k = 0; k < 12; k = k + 1) $write(" %02h", resp[k]); $write("\n");
            end else
                $display("  vector %0d ok", v);
        end
        if (dut.overrun) begin
            $display("FAIL: engine overrun -- an SCL edge arrived while a packet was still being processed");
            errors = errors + 1;
        end

        if (errors == 0) $display("RESULT: PASS"); else $display("RESULT: FAIL (%0d errors)", errors);
        $finish;
    end
endmodule
